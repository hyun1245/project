# EPS : 주당 순이익(Earnings Per Share)
# • 정의: 기업이 1년동안 벌어들인 순이익(당기순이익)을 총 주식수로 나눈 값
# • 계산 공식: 당기순이익 / 총 주식수
# • 활용: EPS가 높을수록 기업의 수익성이 좋음을 의미하며, 투자자들은 EPS를 통해 기업의 수익성을 평가하고 투자를 결정한다. 
#ㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡ
# BPS : 주당순자산가치(Book-value Per Share)
# • 정의: 기업의 총 자산에서 총부채를 뺀 '순자산(자본)' 을 총주식수로 나눈 값
# • 계산 공식: 순자산(총자산 - 총부채) / 총 주식수
# • 활용: BPS가 높을수록 기업이 보유한 자산이 많고 부채가 적음을 의미한다(재무 안정성 높음).
#ㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡ
# PER : 주가 수익 비율(Price Earnings Ratio)
# • 정의: 현재 주가를 EPS(주당순이익)로 나눈값
# • 계산 공식: 현재 주가 / EPS
# • 활용: PER이 낮을수록 주가가 저평가 되어있음을 의미. 일반적으로 PER이 10~15배 사이면 적정 수준으로 본다.
#ㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡ
# PBR : 주가 순자산 비율(Price to Book-value Ratio)
# • 정의: 현재 주가를 BPS(주당순자산가치)로 나눈값
# • 계산 공식: 현재 주가 / BPS
# • 활용: PBR이 1배 미만이면 주가가 장부상 청산가치보다도 낮아 저평가 되어있음을 의미. 일반적으로 PBR이 1~1.5배 사이면 적정 수준으로 본다.
#ㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡㅡ
